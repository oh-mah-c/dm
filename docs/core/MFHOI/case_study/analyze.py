"""Case study on Online Retail: maximal high occupancy itemsets (MHOIs) versus
maximal frequent itemsets (MFIs) at the support threshold ceil(xi).

Run from this directory after prepare_online_retail.py:
  python3 analyze.py <xi as a fraction of the number of transactions>
It runs mfho_miner (MHOIs), LCM ver. 5.3 (MFIs at support ceil(xi)) and
hoi_filter (number of HOIs), computes exact statistics of the itemsets from the database, and
writes case_study_macros.tex and case_study_table.tex for the paper.
"""
import math
import re
import statistics
import subprocess
import sys
from fractions import Fraction
from pathlib import Path

BIN = "../../../../build/bin/mfho_miner"
BIN_HOI = "../../../../build/bin/hoi_filter"
LCM = "../../../../build/bin/lcm53"
DB = Path("data/online_retail.txt")


def load():
    trans = [frozenset(map(int, line.split())) for line in open(DB) if line.strip()]
    names = {}
    for line in open("data/items.tsv"):
        i, code, desc = line.rstrip("\n").split("\t")
        names[int(i)] = desc.strip().lower()
    return trans, names


def read_sets(path):
    # LCM may append " (support)"; keep the item ids only
    return [frozenset(int(v) for v in line.split("(")[0].split()) for line in open(path) if line.split("(")[0].strip()]


def stats(X, trans, index):
    cover = set.intersection(*(index[i] for i in X))
    lens = [len(trans[t]) for t in cover]
    occ = len(X) * sum(Fraction(1, L) for L in lens)
    return {"size": len(X), "supp": len(cover), "occ": occ, "med_len": statistics.median(lens)}


def main(xi_rel):
    trans, names = load()
    n = len(trans)
    index = {}
    for t, items in enumerate(trans):
        for i in items:
            index.setdefault(i, set()).add(t)
    xi = Fraction(xi_rel) * n
    sigma = math.ceil(xi)

    subprocess.run([BIN, str(DB), xi_rel, "0", "--sum", "--out", "mhoi.txt"], check=True, capture_output=True)
    # MFIs at support sigma, with LCM ver. 5.3 (Uno et al.)
    subprocess.run([LCM, "M", str(DB), str(sigma), "mfi.txt"], check=True, capture_output=True)
    p = subprocess.run([BIN_HOI, str(DB), xi_rel, "0", "--mode", "dfhoi", "--sum"], check=True,
                       capture_output=True, text=True)
    num_hoi = int(re.search(r"\bhoi=(\d+)", p.stdout).group(1))

    mhoi, mfi = read_sets("mhoi.txt"), read_sets("mfi.txt")
    S_mhoi = [stats(X, trans, index) for X in mhoi]
    S_mfi = [stats(X, trans, index) for X in mfi]
    assert all(s["occ"] >= xi for s in S_mhoi)
    mfi_set = set(mfi)
    mhoi_in_mfi = sum(1 for X in mhoi if X in mfi_set)
    mfi_hoi = sum(1 for s in S_mfi if s["occ"] >= xi)

    def med(S, k):
        return statistics.median(float(s[k]) for s in S) if S else float("nan")

    lens = [len(t) for t in trans]
    macros = {
        "CsTransactions": f"{n:,}", "CsItems": f"{len(index):,}",
        "CsAvgLen": f"{statistics.mean(lens):.1f}", "CsMedLen": f"{statistics.median(lens):.0f}",
        "CsMaxLen": f"{max(lens):,}",
        "CsXiRel": f"{float(xi_rel) * 100:g}\\%", "CsXiAbs": f"{float(xi):.2f}", "CsSigma": f"{sigma}",
        "CsNumHOI": f"{num_hoi:,}", "CsNumMHOI": f"{len(mhoi):,}", "CsNumMFI": f"{len(mfi):,}",
        "CsMHOIinMFI": f"{mhoi_in_mfi}", "CsMHOISingle": f"{sum(1 for X in mhoi if len(X) == 1)}",
        "CsMHOIMulti": f"{sum(1 for X in mhoi if len(X) >= 2)}", "CsMHOIMaxSize": f"{max(len(X) for X in mhoi)}", "CsMFIisHOI": f"{mfi_hoi}",
        "CsMHOIMedSize": f"{med(S_mhoi, 'size'):.0f}", "CsMFIMedSize": f"{med(S_mfi, 'size'):.0f}",
        "CsMHOIMedSupp": f"{med(S_mhoi, 'supp'):.0f}", "CsMFIMedSupp": f"{med(S_mfi, 'supp'):.0f}",
        "CsMHOIMedOcc": f"{med(S_mhoi, 'occ'):.1f}", "CsMFIMedOcc": f"{med(S_mfi, 'occ'):.1f}",
        "CsMHOIMedLen": f"{med(S_mhoi, 'med_len'):.0f}", "CsMFIMedLen": f"{med(S_mfi, 'med_len'):.0f}",
    }
    with open("case_study_macros.tex", "w") as f:
        f.write("% Generated by case_study/analyze.py -- do not edit by hand.\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    def write_rows(f, rows):
        for X, s in rows:
            desc = "; ".join(sorted(" ".join(names[i].split()) for i in X)).replace("&", "\\&").replace("%", "\\%")
            f.write(f"{desc} & {s['size']} & {s['supp']} & {s['med_len']:.0f} & {float(s['occ']):.1f} \\\\\n")

    multi = sorted([p for p in zip(mhoi, S_mhoi) if p[1]["size"] >= 2], key=lambda p: (-p[1]["occ"], -p[1]["supp"]))
    single = sorted([p for p in zip(mhoi, S_mhoi) if p[1]["size"] == 1], key=lambda p: (-p[1]["occ"], -p[1]["supp"]))[:3]
    top_mfi = sorted(zip(mfi, S_mfi), key=lambda p: (-p[1]["supp"], -p[1]["occ"]))[:3]
    with open("case_study_table.tex", "w") as f:
        f.write("\\multicolumn{5}{@{}l}{\\emph{All MHOIs with two or more products}} \\\\\n")
        write_rows(f, multi)
        f.write("\\midrule\n\\multicolumn{5}{@{}l}{\\emph{Single-product MHOIs with the highest occupancy}} \\\\\n")
        write_rows(f, single)
        f.write("\\midrule\n\\multicolumn{5}{@{}l}{\\emph{MFIs with the highest support}} \\\\\n")
        write_rows(f, top_mfi)
    for k, v in macros.items():
        print(k, v)


if __name__ == "__main__":
    main(sys.argv[1])
